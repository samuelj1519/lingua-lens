#!/usr/bin/env node
// Generate docs locale reference/settings.md from contributes/configuration.json + package.nls JSON.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');

function loadJson(p) {
  return JSON.parse(fs.readFileSync(p, 'utf8'));
}

function resolveNls(template, nls) {
  if (!template || typeof template !== 'string') return template ?? '';
  return template.replace(/%([^%]+)%/g, (_, key) => nls[key] ?? `%${key}%`);
}

function flattenProperties(sections) {
  const rows = [];
  for (const section of sections) {
    const title = section.title;
    for (const [key, schema] of Object.entries(section.properties ?? {})) {
      rows.push({ sectionTitle: title, key, schema });
    }
  }
  return rows;
}

function formatDefault(v) {
  if (v === undefined) return '—';
  return '`' + JSON.stringify(v).replace(/`/g, '\\`') + '`';
}

function generate(locale, nlsFile, outFile) {
  const sections = loadJson(path.join(root, 'contributes/configuration.json'));
  const nls = loadJson(path.join(root, nlsFile));
  const rows = flattenProperties(sections);
  const lines = [
    '# Settings reference',
    '',
    locale === 'zh-CN'
      ? '> 由 `scripts/generate-settings-reference.mjs` 自动生成，请勿手改。'
      : '> Auto-generated by `scripts/generate-settings-reference.mjs`. Do not edit by hand.',
    '',
    '| Setting | Type | Default | Description |',
    '| --- | --- | --- | --- |',
  ];
  for (const { sectionTitle, key, schema } of rows) {
    const desc = resolveNls(schema.markdownDescription ?? schema.description ?? '', nls);
    const section = resolveNls(sectionTitle, nls);
    const type = schema.enum ? `enum (${schema.enum.map((e) => '`' + e + '`').join(', ')})` : schema.type ?? '—';
    const def = formatDefault(schema.default);
    const cell = desc.replace(/\|/g, '\\|').replace(/\n/g, ' ');
    lines.push(`| \`${key}\` | ${type} | ${def} | **${section}** — ${cell} |`);
  }
  lines.push('');
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, lines.join('\n'));
}

generate('en', 'package.nls.json', path.join(root, 'docs/en/reference/settings.md'));
generate('zh-CN', 'package.nls.zh-cn.json', path.join(root, 'docs/zh-CN/reference/settings.md'));
console.log('Wrote docs/en/reference/settings.md and docs/zh-CN/reference/settings.md');
