#!/usr/bin/env node
// ALLOW_CJK_LOCALE_DATA: embedded zh-CN markdown templates for generated docs.
// Generate docs/{en,zh-CN}/reference/settings.md from contributes/configuration.json + package.nls*.json
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');

function loadJson(p) {
  return JSON.parse(fs.readFileSync(p, 'utf8'));
}

function resolveNls(template, nls) {
  if (!template || typeof template !== 'string') return template ?? '';
  return template.replace(/%([^%]+)%/g, (_, key) => nls[key] ?? `%${key}%`);
}

function stripSettingsLinks(md) {
  return md.replace(/\[#linguaLens\.[^#]+#\]\(settings:\/\/[^)]+\)/g, '`linguaLens.*` cross-link');
}

function formatDefault(v) {
  if (v === undefined) return '_none_';
  return '`' + JSON.stringify(v) + '`';
}

function formatType(schema) {
  if (schema.enum) {
    const vals = schema.enum.map((e) => `\`${e}\``).join(', ');
    return `enum: ${vals}`;
  }
  if (schema.type === 'array') {
    const item = schema.items?.type ? ` of ${schema.items.type}` : '';
    return `array${item}`;
  }
  return schema.type ?? 'unknown';
}

function formatConstraints(schema) {
  const parts = [];
  if (schema.minimum !== undefined) parts.push(`min ${schema.minimum}`);
  if (schema.maximum !== undefined) parts.push(`max ${schema.maximum}`);
  if (schema.tags?.includes('advanced')) parts.push('advanced');
  return parts.length ? ` (${parts.join(', ')})` : '';
}

function generate(locale, nlsFile, outFile) {
  const sections = loadJson(path.join(root, 'contributes/configuration.json'));
  const nls = loadJson(path.join(root, nlsFile));
  const intro =
    locale === 'zh-CN'
      ? [
          '# 设置参考',
          '',
          '> 本文档由 `scripts/generate-settings-reference.mjs` 根据 `contributes/configuration.json` 与 `package.nls.*` 自动生成。请勿手改；修改配置或文案后重新运行 `npm run generate-docs`。',
          '',
          '所有键均在 VS Code 设置中显示为 `linguaLens.<key>`。下表按设置 UI 的七个分组排列。',
          '',
        ]
      : [
          '# Settings reference',
          '',
          '> Auto-generated by `scripts/generate-settings-reference.mjs` from `contributes/configuration.json` and `package.nls.*`. Do not edit by hand—run `npm run generate-docs` after changing configuration or nls strings.',
          '',
          'Keys appear in VS Code settings as `linguaLens.<key>`. Sections match the seven groups in the settings UI.',
          '',
        ];

  const lines = [...intro];
  let total = 0;

  for (const section of sections) {
    const sectionTitle = resolveNls(section.title, nls);
    lines.push(`## ${sectionTitle}`, '');
    const props = section.properties ?? {};
    for (const [key, schema] of Object.entries(props)) {
      total++;
      const shortKey = key.replace(/^linguaLens\./, '');
      const desc = stripSettingsLinks(
        resolveNls(schema.markdownDescription ?? schema.description ?? '', nls),
      );
      lines.push(`### \`${shortKey}\``, '');
      lines.push(`- **Type:** ${formatType(schema)}${formatConstraints(schema)}`);
      lines.push(`- **Default:** ${formatDefault(schema.default)}`);
      lines.push(`- **Scope:** \`${schema.scope ?? 'window'}\``);
      if (schema.enum && schema.enumDescriptions) {
        lines.push('- **Enum values:**');
        schema.enum.forEach((val, i) => {
          const ed = resolveNls(schema.enumDescriptions[i] ?? '', nls);
          lines.push(`  - \`${val}\` — ${ed}`);
        });
      }
      lines.push(`- **Description:** ${desc.replace(/\n/g, ' ')}`, '');
    }
  }

  lines.push('---', '', `_Total settings: ${total}_`, '');
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, lines.join('\n'));
  return total;
}

const enCount = generate('en', 'package.nls.json', path.join(root, 'docs/en/reference/settings.md'));
generate('zh-CN', 'package.nls.zh-cn.json', path.join(root, 'docs/zh-CN/reference/settings.md'));
console.log(`Wrote settings reference (${enCount} settings) for en and zh-CN`);
