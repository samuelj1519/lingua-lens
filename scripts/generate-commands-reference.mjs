#!/usr/bin/env node
// ALLOW_CJK_LOCALE_DATA: embedded zh-CN markdown templates for generated docs.
// Generate docs/{en,zh-CN}/reference/commands.md from package.json contributes + package.nls*.json
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkg = loadJson(path.join(root, 'package.json'));

function loadJson(p) {
  return JSON.parse(fs.readFileSync(p, 'utf8'));
}

function resolveNls(template, nls) {
  if (!template || typeof template !== 'string') return template;
  return template.replace(/%([^%]+)%/g, (_, key) => nls[key] ?? `%${key}%`);
}

function paletteVisible(commandId, menus) {
  const entry = menus.commandPalette?.find((m) => m.command === commandId);
  if (!entry) return true;
  return entry.when !== 'false';
}

function contextMenus(commandId, menus) {
  const places = [];
  if (menus['editor/context']?.some((m) => m.command === commandId)) places.push('editor context');
  if (menus['editor/title']?.some((m) => m.command === commandId)) places.push('editor title');
  if (menus['explorer/context']?.some((m) => m.command === commandId)) places.push('explorer context');
  return places;
}

function keybinding(commandId, keybindings) {
  const kb = keybindings.find((k) => k.command === commandId);
  if (!kb) return '—';
  const mac = kb.mac ? ` / mac: \`${kb.mac}\`` : '';
  const when = kb.when ? ` (when: \`${kb.when}\`)` : '';
  return `\`${kb.key}\`${mac}${when}`;
}

function generate(locale, nlsFile, outFile) {
  const nls = loadJson(path.join(root, nlsFile));
  const commands = pkg.contributes.commands ?? [];
  const keybindings = pkg.contributes.keybindings ?? [];
  const menus = pkg.contributes.menus ?? {};
  const codelens = pkg.contributes['languages'] ?? [];

  const intro =
    locale === 'zh-CN'
      ? [
          '# 命令与快捷键',
          '',
          '> 由 `scripts/generate-commands-reference.mjs` 根据 `package.json` 的 `contributes` 自动生成。',
          '',
          '命令面板中的标题格式为 **LinguaLens: …**（`category` 为 `LinguaLens`）。悬停内链命令（`aiTranslate.hover.*`）默认不在命令面板中列出（`when: false`）。',
          '',
        ]
      : [
          '# Commands and keybindings',
          '',
          '> Auto-generated by `scripts/generate-commands-reference.mjs` from `package.json` contributes.',
          '',
          'Command palette titles appear as **LinguaLens: …** (`category` is `LinguaLens`). Hover-only commands (`aiTranslate.hover.*`) are hidden from the palette (`when: false`).',
          '',
        ];

  const lines = [...intro, '| Command ID | Title | Keybinding | Surfaces |', '| --- | --- | --- | --- |'];

  for (const cmd of commands) {
    const title = resolveNls(cmd.title, nls);
    const id = cmd.command;
    const kb = keybinding(id, keybindings);
    const surfaces = [];
    if (paletteVisible(id, menus)) surfaces.push('command palette');
    surfaces.push(...contextMenus(id, menus));
    if (id === 'aiTranslate.openSettingsPanel') surfaces.push('status bar QuickPick');
    if (id === 'aiTranslate.showQuickPick') surfaces.push('status bar');
    if (
      id === 'aiTranslate.translateDocument' ||
      id === 'aiTranslate.refreshDocumentTranslation' ||
      id === 'aiTranslate.generateSideFile'
    ) {
      surfaces.push('CodeLens (Markdown)');
    }
    if (id.startsWith('aiTranslate.hover.')) surfaces.push('hover markdown link');
    const uniq = [...new Set(surfaces)].join(', ') || '—';
    lines.push(`| \`${id}\` | ${title.replace(/\|/g, '\\|')} | ${kb} | ${uniq} |`);
  }

  lines.push(
    '',
    '## CodeLens',
    '',
    locale === 'zh-CN'
      ? 'Markdown / 纯文本编辑器在文件顶部显示 **翻译全文（对照预览）**、**生成译文文件**、**刷新全文翻译**（预览已打开时）等 CodeLens，具体文案来自 `l10n/bundle`（跟随 `aiTranslate.targetLanguage`）。'
      : 'Markdown/plain-text editors show **Translate document (preview)**, **Generate translation file**, and **Refresh document translation** at the top of the file. Wording comes from `l10n/bundle` (follows `aiTranslate.targetLanguage`).',
    '',
    '## Status bar',
    '',
    locale === 'zh-CN'
      ? '右侧 **Tr/译** 图标打开 QuickPick（启用/禁用、目标语言、设置面板、翻译全文等）；相邻项显示当前 `targetLanguage`。'
      : 'The **Tr** status item opens a QuickPick (enable/disable, target language, settings panel, translate document, …). The neighbor item shows the current `targetLanguage`.',
    '',
  );

  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, lines.join('\n'));
}

generate('en', 'package.nls.json', path.join(root, 'docs/en/reference/commands.md'));
generate('zh-CN', 'package.nls.zh-cn.json', path.join(root, 'docs/zh-CN/reference/commands.md'));
console.log('Wrote commands reference for en and zh-CN');
